#!/usr/bin/env python3
"""Write the MEGSINE MHC0410L03 footprint and symbol (rerun to regenerate; UUIDs derive from names).

usage: gen_mhc.py   (run from antenna_top_cap_v3/)
Land pattern from the datasheet outline (rev 2, 2026-07-24): body 14.22 x 8.89 mm, four L-shaped corner
terminals (legs 1 mm wide, inner edges at x 4.51 and y 1.845), ground everywhere else under the body.
Top view: pin 1 top left, 2 top right, 3 bottom right, 4 bottom left.
"""
import uuid

NS = uuid.UUID("6f1d5b0e-4c1e-4b57-9a65-0d0c52139893")
BX, BY = 7.11, 4.445  # half body
TOE = 0.10  # land past the body edge
XI, YI, LEG = 4.51, 1.845, 1.0
GAP = 0.5  # signal land to ground land


def u(*p):
    return str(uuid.uuid5(NS, "/".join(map(str, p))))


def poly(pts):
    return " ".join(f"(xy {x:.3f} {y:.3f})" for x, y in pts)


def custom(num, sx, sy):
    ax, ay = sx * (XI + LEG / 2), sy * (YI + LEG / 2)  # anchor: the corner of the L
    pts = [(XI, YI), (BX + TOE, YI), (BX + TOE, YI + LEG), (XI + LEG, YI + LEG), (XI + LEG, BY + TOE), (XI, BY + TOE)]
    rel = [(sx * x - ax, sy * y - ay) for x, y in pts]
    return (f'\t(pad "{num}" smd custom\n\t\t(at {ax:.3f} {ay:.3f})\n\t\t(size {LEG} {LEG})\n\t\t(layers "F.Cu" "F.Mask" "F.Paste")\n'
            f'\t\t(options\n\t\t\t(clearance outline)\n\t\t\t(anchor rect)\n\t\t)\n'
            f'\t\t(primitives\n\t\t\t(gr_poly\n\t\t\t\t(pts {poly(rel)})\n\t\t\t\t(width 0)\n\t\t\t\t(fill yes)\n\t\t\t)\n\t\t)\n'
            f'\t\t(uuid "{u("pad", num)}")\n\t)\n')


def rect(num, x, y, w, h, layers, tag):
    return (f'\t(pad "{num}" smd rect\n\t\t(at {x:.3f} {y:.3f})\n\t\t(size {w:.3f} {h:.3f})\n\t\t(layers {layers})\n\t\t(zone_connect 2)\n'
            f'\t\t(uuid "{u("pad", tag)}")\n\t)\n')


def via(x, y):
    return (f'\t(pad "5" thru_hole circle\n\t\t(at {x:.3f} {y:.3f})\n\t\t(size 0.6 0.6)\n\t\t(drill 0.3)\n\t\t(layers "*.Cu")\n'
            f'\t\t(remove_unused_layers no)\n\t\t(zone_connect 2)\n\t\t(uuid "{u("via", x, y)}")\n\t)\n')


def line(x0, y0, x1, y1, layer, w):
    return (f'\t(fp_line\n\t\t(start {x0:.3f} {y0:.3f})\n\t\t(end {x1:.3f} {y1:.3f})\n\t\t(stroke\n\t\t\t(width {w})\n\t\t\t(type solid)\n\t\t)\n'
            f'\t\t(layer "{layer}")\n\t\t(uuid "{u("ln", layer, x0, y0, x1, y1)}")\n\t)\n')


def box(hx, hy, layer, w):
    return "".join(line(*s, layer, w) for s in [(-hx, -hy, hx, -hy), (hx, -hy, hx, hy), (hx, hy, -hx, hy), (-hx, hy, -hx, -hy)])


def text_prop(name, value, y, layer, hide=False):
    h = "\n\t\t(hide yes)" if hide else ""
    return (f'\t(property "{name}" "{value}"\n\t\t(at 0 {y} 0)\n\t\t(layer "{layer}"){h}\n\t\t(uuid "{u("prop", name)}")\n'
            f'\t\t(effects\n\t\t\t(font\n\t\t\t\t(size 0.8 0.8)\n\t\t\t\t(thickness 0.12)\n\t\t\t)\n\t\t)\n\t)\n')


DS = "https://datasheet.lcsc.com/datasheet/pdf/46836830f8b0c6affe7c26a253a585e6.pdf"
fp = ('(footprint "MHC0410L03"\n\t(version 20241229)\n\t(generator "pcbnew")\n\t(generator_version "9.0")\n\t(layer "F.Cu")\n'
      '\t(descr "MEGSINE MHC0410L03 3 dB 90 degree hybrid, 14.22 x 8.89 mm, generated by tools/gen_mhc.py")\n')
fp += text_prop("Reference", "REF**", -5.6, "F.SilkS")
fp += text_prop("Value", "MHC0410L03", 5.6, "F.Fab")
fp += text_prop("Datasheet", DS, 0, "F.Fab", hide=True)
fp += text_prop("Description", "3 dB 90 degree hybrid coupler, 400-1000 MHz", 0, "F.Fab", hide=True)
fp += "\t(attr smd)\n"
fp += box(BX, BY, "F.Fab", 0.1) + box(BX + 0.35, BY + 0.35, "F.CrtYd", 0.05)
for sx in (-1, 1):  # silk only along the long sides between the terminals
    fp += line(-XI + 0.4, sx * (BY + 0.25), XI - 0.4, sx * (BY + 0.25), "F.SilkS", 0.12)
fp += (f'\t(fp_circle\n\t\t(center {-BX - 0.6:.3f} {-BY + 0.4:.3f})\n\t\t(end {-BX - 0.45:.3f} {-BY + 0.4:.3f})\n\t\t(stroke\n\t\t\t(width 0.15)\n\t\t\t(type solid)\n\t\t)\n'
       f'\t\t(fill yes)\n\t\t(layer "F.SilkS")\n\t\t(uuid "{u("pin1")}")\n\t)\n')
for num, sx, sy in (("1", -1, -1), ("2", 1, -1), ("3", 1, 1), ("4", -1, 1)):
    fp += custom(num, sx, sy)
CU = '"F.Cu" "F.Mask"'
fp += rect("5", 0, 0, 2 * (XI - GAP), 2 * (BY + TOE), CU, "gnd-centre")
fp += rect("5", 0, 0, 2 * (BX + TOE), 2 * (YI - GAP), CU, "gnd-ends")
for x in (-2.4, 2.4):  # paste in four windows so the body does not float
    for y in (-2.6, 2.6):
        fp += rect("5", x, y, 3.0, 2.6, '"F.Paste"', f"paste{x}{y}")
for x in (-3.2, -1.6, 0, 1.6, 3.2):
    for y in (-0.6, 0.6):
        fp += via(x, y)
for x in (-6.2, 6.2):
    fp += via(x, 0)
fp += "\t(embedded_fonts no)\n)\n"
open("footprints.pretty/MHC0410L03.kicad_mod", "w").write(fp)


def pin(num, name, x, y, ang, kind="passive", namesize=1.27):
    return (f'\t\t\t(pin {kind} line\n\t\t\t\t(at {x} {y} {ang})\n\t\t\t\t(length 2.54)\n'
            f'\t\t\t\t(name "{name}"\n\t\t\t\t\t(effects\n\t\t\t\t\t\t(font\n\t\t\t\t\t\t\t(size {namesize} {namesize})\n\t\t\t\t\t\t)\n\t\t\t\t\t)\n\t\t\t\t)\n'
            f'\t\t\t\t(number "{num}"\n\t\t\t\t\t(effects\n\t\t\t\t\t\t(font\n\t\t\t\t\t\t\t(size 1.27 1.27)\n\t\t\t\t\t\t)\n\t\t\t\t\t)\n\t\t\t\t)\n\t\t\t)\n')


def sprop(name, value, x, y, hide=False):
    h = "\n\t\t\t\t(hide yes)" if hide else ""
    return (f'\t\t(property "{name}" "{value}"\n\t\t\t(at {x} {y} 0)\n\t\t\t(effects\n\t\t\t\t(font\n\t\t\t\t\t(size 1.27 1.27)\n\t\t\t\t){h}\n\t\t\t)\n\t\t)\n')


sym = ('\t(symbol "MHC0410L03"\n\t\t(exclude_from_sim no)\n\t\t(in_bom yes)\n\t\t(on_board yes)\n'
       + sprop("Reference", "U", -10.16, 8.89) + sprop("Value", "MHC0410L03", 0, 0, hide=True)
       + sprop("Footprint", "Antenna_board:MHC0410L03", 0, 0, hide=True) + sprop("Datasheet", DS, 0, 0, hide=True)
       + sprop("Description", "3 dB 90 degree hybrid coupler, 400-1000 MHz, 100 W", 0, 0, hide=True)
       + '\t\t(symbol "MHC0410L03_1_1"\n'
       '\t\t\t(rectangle\n\t\t\t\t(start -10.16 7.62)\n\t\t\t\t(end 10.16 -7.62)\n\t\t\t\t(stroke\n\t\t\t\t\t(width 0.1524)\n\t\t\t\t\t(type solid)\n\t\t\t\t)\n'
       '\t\t\t\t(fill\n\t\t\t\t\t(type background)\n\t\t\t\t)\n\t\t\t)\n'
       + pin("1", "P1", -12.7, 2.54, 0) + pin("2", "P2", -12.7, -2.54, 0)
       + pin("3", "P3", 12.7, -2.54, 180) + pin("4", "P4", 12.7, 2.54, 180)
       + pin("5", "GND", 0, -10.16, 90, kind="power_in")
       + '\t\t)\n\t\t(embedded_fonts no)\n\t)\n')
lib = open("symbols/turnstile_rf.kicad_sym").read()
i = lib.find('\t(symbol "MHC0410L03"')
if i >= 0:
    lib = lib[:i].rstrip("\n") + "\n)\n"
lib = lib.rstrip().rstrip(")").rstrip() + "\n" + sym + ")\n"
open("symbols/turnstile_rf.kicad_sym", "w").write(lib)
print("wrote footprint and symbol")
